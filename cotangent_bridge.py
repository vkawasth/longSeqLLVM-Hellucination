# THE FLOER APPROXIMATION: linearised Hamiltonian flow
# ─────────────────────────────────────────────────────────────────

@dataclass
class FloerApproximation:
    """
    The Floer continuation map, approximated by the linearised Hamiltonian flow.
    
    CLAIM: T_{k,k+1} = dφ_1|_{h_k} (Jacobian of Hamiltonian flow)
    COMPUTE: T_{k,k+1} = arg min ||TH_k - H_{k+1}||_F (LS fit)
    
    GAP: LS fit ≈ Jacobian only when the flow is close to linear.
    The approximation error is the cup error = m_3.
    
    WHAT THIS SHOWS: The transport operator is the best linear approximation
    to the (nonlinear) continuation map. The composition failure (cup error)
    is the first nonlinear correction — it IS m_3 in the A_∞ sense.
    
    WHAT THIS DOES NOT SHOW: The actual Floer homology groups, which require
    counting J-holomorphic strips, not just linearising the flow.
    """
    T:                np.ndarray    # linearised transport (LS fit)
    jacobian:         np.ndarray    # actual Jacobian via finite difference
    linearisation_error: float      # ||T - Jacobian|| / ||Jacobian||
    cup_error:        float         # composition failure = m_3
    is_valid_approx:  bool          # linearisation error < threshold


def compute_floer_approximation(
    h_before: np.ndarray,   # hidden states before transition [n, d]
    h_after:  np.ndarray,   # hidden states after transition [n, d]
    keys_b:   np.ndarray,   # keys for attention energy before
    keys_a:   np.ndarray,   # keys for attention energy after
    W_Q:      Optional[np.ndarray] = None,
    eps:      float = 1e-4,
) -> FloerApproximation:
    """
    Compute the Floer approximation: linearised Hamiltonian flow vs LS transport.
    """
    from bv_calculus import fit_transport
    d = h_before.shape[1]
    if W_Q is None:
        W_Q = np.eye(d)

    # LS-fitted transport (our standard T)
    T = fit_transport(h_before, h_after, rank=None)

    # Numerical Jacobian of Hamiltonian flow
    # φ_1(h) ≈ h + ∇_h E_after(h) - ∇_h E_before(h)  [symplectic Euler step]
    mu_b = h_before.mean(0)
    d_used = min(d, len(mu_b))

    Jac = np.zeros((d_used, d_used))
    for i in range(d_used):
        h_plus  = mu_b.copy(); h_plus[i]  += eps
        h_minus = mu_b.copy(); h_minus[i] -= eps
        _, xi_p_b = attention_energy(h_plus[:d_used],  keys_b[:, :d_used], W_Q[:d_used,:d_used])
        _, xi_m_b = attention_energy(h_minus[:d_used], keys_b[:, :d_used], W_Q[:d_used,:d_used])
        _, xi_p_a = attention_energy(h_plus[:d_used],  keys_a[:, :d_used], W_Q[:d_used,:d_used])
        _, xi_m_a = attention_energy(h_minus[:d_used], keys_a[:, :d_used], W_Q[:d_used,:d_used])
        # Hamiltonian flow step: h → h + (∇E_after - ∇E_before)
        flow_p = h_plus[:d_used]  + (xi_p_a - xi_p_b)
        flow_m = h_minus[:d_used] + (xi_m_a - xi_m_b)
        Jac[:, i] = (flow_p - flow_m) / (2 * eps)

    T_d = T[:d_used, :d_used]
    lin_err = float(np.linalg.norm(T_d - Jac, 'fro') /
                    (np.linalg.norm(Jac, 'fro') + 1e-8))

    # Cup error: how much does T fail to compose
    T12 = fit_transport(h_before, h_after[:len(h_before)])
    T23 = fit_transport(h_after[:len(h_before)], h_after)
    T13 = fit_transport(h_before, h_after)
    cup = float(np.linalg.norm(T12 @ T23 - T13, 'fro') /
                (np.linalg.norm(T13, 'fro') + 1e-8))

    return FloerApproximation(
        T=T, jacobian=Jac,
        linearisation_error=lin_err,
        cup_error=cup,
        is_valid_approx=lin_err < 0.5,
    )


